# Writes dev/cet/sound-sweep.lua from the event map (event-map.py's output, a TSV): one weapon per
# auto-fire or burst fill, crafted with the matching trigger mod (plus Barrel_Silencer for a
# _suppressor set), so the Phase 3 full proof can fire every patched set once in a loaded save.
# Usage: python sound-sweep.py <out.lua> <event-map.tsv> [dev/spike/audioware/gap-fills.tsv ...]
# (gap-fills.tsv: the fills the Phase 3 gate added, in the same row form; # lines are skipped)
import sys

# Weapons whose suppressor is built in: they use their _suppressor set without a silencer, and
# with Barrel_Silencer added Panam's Grad played no watched event at all (Phase 3 full proof).
BUILT_IN_SUPPRESSOR = ("Grad_Panam",)

TRIGGER = {"autoFireSound": ("Trigger_FullAuto", "FullAuto"), "burstFireSound": ("Trigger_Burst", "Burst")}

rows = []
lines = [l for p in sys.argv[2:] for l in open(p, encoding="utf-8") if not l.startswith("#")]
for line in lines:
    kind, sset, field, _vanilla, event, weapons = line.rstrip("\n").split("\t")
    if kind != "fill" or field not in TRIGGER:
        continue
    names = [w.strip() for w in weapons.split(":", 1)[1].replace("...", "").split(",") if w.strip()]
    plain = [w for w in names if "Left_Hand" not in w]
    pick = next((w for w in plain if w.endswith("_Default")), plain[0] if plain else names[0])
    trigger, mode = TRIGGER[field]
    silencer = sset.endswith("_suppressor") and not pick.startswith(BUILT_IN_SUPPRESSOR)
    mods = ("Barrel_Silencer, " if silencer else "") + trigger
    rows.append((sset, field, "Items.Preset_" + pick, mods, mode, event))

with open(sys.argv[1], "w", encoding="utf-8", newline="\n") as out:
    out.write("""-- Dev only. Generated by dev/spike/audioware/sound-sweep.py from the event map; don't edit.
-- Phase 3 full proof: fires one weapon per auto-fire or burst fill of PreemSoundSets, in a loaded save:
--   pwsh tools/boot-check.ps1 -LoadSave -Run dev/cet/sound-sweep.lua -HoldSec %d
-- Each line of the result is "[PreemDev] sound: <event> on player's weapon <record>"; the expected
-- event per weapon is the last field below. Same steps as dev/cet/sound-check.lua.
local sweep = {
""" % (len(rows) * 9 + 20))
    for r in rows:
        out.write('  { set = "%s", field = "%s", weapon = "%s", mods = "%s", mode = "%s", expect = "%s" },\n' % r)
    out.write("""}
local ammo = { "Ammo.HandgunAmmo", "Ammo.RifleAmmo", "Ammo.ShotgunAmmo", "Ammo.SniperRifleAmmo" }

local watch, seen = {}, {}
for _, s in ipairs(sweep) do
  -- an auto loop's stop event is the loop's name + "_stop" for every donor
  for _, e in ipairs({ s.expect, s.field == "autoFireSound" and s.expect .. "_stop" or nil }) do
    if not seen[e] then seen[e] = true; table.insert(watch, e) end
  end
end

local steps = { { at = 0, run = function()
  Game.PreemSoundWatch(table.concat(watch, ", "))
  for _, a in ipairs(ammo) do Game.AddToInventory(a, 3000) end
end } }
for n, s in ipairs(sweep) do
  local t = (n - 1) * 9
  table.insert(steps, { at = t, run = function()
    print(string.format("[PreemSweep] %d %s %s expect %s", n, s.set, s.weapon, s.expect))
    Game.PreemCraftTest(s.weapon, s.mods)
  end })
  table.insert(steps, { at = t + 2, run = function() Game.PreemEquipTest() end })
  table.insert(steps, { at = t + 4, run = function() Game.PreemSoundDraw() end })
  for i = 0, 7 do
    table.insert(steps, { at = t + 6.5 + i * 0.15, run = function() Game.PreemSoundFire(s.mode) end })
  end
end
table.insert(steps, { at = #sweep * 9 + 3, run = function() Game.PreemSoundSummary() end })
table.sort(steps, function(a, b) return a.at < b.at end)

local startTime, playingFor, nextStep = nil, nil, 1

registerForEvent("onUpdate", function(delta)
  if nextStep > #steps then return end
  if playingFor == nil then
    if not Game.GetPlayer() or Game.GetSystemRequestsHandler():IsPreGame() then return end
    local now = Game.GetTimeSystem():GetGameTimeStamp()
    if startTime == nil then startTime = now elseif now > startTime then playingFor = 0 end
    return
  end
  playingFor = playingFor + delta
  while nextStep <= #steps and playingFor - 3 >= steps[nextStep].at do
    steps[nextStep].run()
    nextStep = nextStep + 1
  end
end)
""")
print("%d weapons" % len(rows))
